      return [
        for (var i = 1; i <= _maxPhotosPerPlace; i++) _supabasePhotoUrl(id, i),
      ];
    }

    // Mode demo local (Supabase absent) → assets locaux.
    return [
      for (var i = 1; i <= 5; i++) 'assets/places/${id}_$i.jpg',
    ];
