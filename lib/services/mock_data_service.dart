  /// Enrichit chaque lieu (medias + donnees derivees pour les filtres avances).
  ///
  /// >>> POINT DE BRANCHEMENT BACKEND <<<
  /// Le prix reel, la frequentation et les horaires d'affluence sont ici
  /// DERIVES de façon deterministe a partir du type/prix/tags (heuristiques
  /// de demo). Quand un backend sera branche, ces valeurs viendront de vraies
  /// donnees (ex: Google Popular Times, tickets moyens, etc.).
  Place _withMockMedia(Place p) {
    final ambiance = [...p.ambianceTags];
    // "calme" : intimiste/cosy sans cote festif/anime.
    if ((ambiance.contains('intimiste') || ambiance.contains('cosy')) &&
        !ambiance.contains('festif') &&
        !ambiance.contains('animé')) {
      ambiance.add('calme');
    }

    final style = [...p.styleTags];
    // "luxueux" : haut de gamme (prix 4, palace ou premium).
    if (p.priceLevel >= 4 || style.contains('palace') || p.isPremium) {
      if (!style.contains('luxueux')) style.add('luxueux');
    }

    // Lien Google Maps REEL (recherche par nom + adresse) : ouvre la vraie
    // fiche du lieu avec ses avis reels, photos et itineraire.
    final mapsUrl = 'https://www.google.com/maps/search/?api=1&query='
        '${Uri.encodeComponent('${p.name} ${p.address}')}';
    // Hashtag Instagram (best-effort a partir du nom).
    final slug = p.name
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]'), '');
    final instagramUrl = 'https://www.instagram.com/explore/tags/$slug/';

    return Place(
      id: p.id,
      name: p.name,
      type: p.type,
      latitude: p.latitude,
      longitude: p.longitude,
      address: p.address,
      rating: p.rating,
      reviewCount: p.reviewCount,
      priceLevel: p.priceLevel,
      ambianceTags: ambiance,
      musicTags: p.musicTags,
      styleTags: style,
      photos: _photosForPlace(p.id),
      videos: const [],
      isPremium: p.isPremium,
      averagePrice: _averagePrice(p),
      crowdTags: _crowd(p),
      peakTags: _peak(p),
      mapsUrl: mapsUrl,
      instagramUrl: instagramUrl,
      // websiteUrl laisse a null : on ne fabrique pas de faux site.
      // Extraits "Instagram" : utilise _igVideos[id] si rempli, sinon demo.
      instagramVideos: _igVideosForPlace(p.id),
      // Nos interviews maison : rempli via _originalVideosMap si disponible.
      originalVideos: _originalVideosForPlace(p.id),
      // Extraits d'avis Google : specifiques si disponibles, sinon generes.
      reviews: _reviewSamples[p.id] ?? _generateReviews(p),
    );
